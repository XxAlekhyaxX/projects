def add(n1, n2):
    result = n1 + n2
    return result


def subtract(n1, n2):
    return n1 - n2


def multiply(n1, n2):
    return n1 * n2


def divide(n1, n2):
    if n2 == 0:
        print("cannot divide with zero")
        return None
    return n1 / n2


def power(n1, n2):
    return n1**n2


